/**
 * Writes a Solitude `CreatureProfile` factory for a generated creature, so a BadCreatures GLB
 * drops straight into Solitude's Swimmer (Scripts/Creatures/CreatureProfile.cs).
 *
 * The axes line up 1:1: our bones have identity rest rotations, so Swimmer's per-bone
 * up/right/forward are +Y/+X/+Z, exactly the axes our yaw/pitch/roll channels use, with the same
 * signs. The jaw is an absolute pitch about +X (positive opens); the mesh is sculpted open at rest,
 * so JawClosed is negative.
 */
import type { Creature } from './generate';

const f = (x: number) => `${Math.round(x * 1000) / 1000}f`;
const pascal = (s: string) => s.replace(/(^|[^a-zA-Z0-9]+)([a-zA-Z0-9])/g, (_, __, c) => c.toUpperCase());

/** the model's own extent along Z (what Solitude calls ModelLength) */
export function modelLength(c: Creature): number {
  let lo = Infinity;
  let hi = -Infinity;
  for (const p of c.primitives)
    for (let i = 2; i < p.mesh.positions.length; i += 3) {
      lo = Math.min(lo, p.mesh.positions[i]);
      hi = Math.max(hi, p.mesh.positions[i]);
    }
  return hi - lo;
}

export function solitudeProfile(c: Creature, file = `${c.recipe.species}.glb`): string {
  const m = c.motion;
  const rc = c.recipe;
  const L = rc.length;
  const fn = pascal(rc.name);
  if (m.walk) {
    return `// ${rc.name} walks on legs: Swimmer is for swimmers. Use the baked Walk / Run / Idle / Attack clips\n// in ${file} (front +Z, feet on y = 0), or drive bones ${m.walk.legs.map((l) => l.upper).slice(0, 4).join(', ')}… directly.\n`;
  }
  const cruise = Math.max(0.6, 0.55 * L ** 0.62);
  const lines = [
    `    public static CreatureProfile ${fn}()`,
    `    {`,
    `        // Generated by BadCharacters / BadCreatures: ${rc.species}, seed ${rc.seed}. Front +Z, identity bone rests,`,
    `        // so Yaw/Pitch/Roll below are about the bones' +Y/+X/+Z exactly as Swimmer applies them.`,
    `        var p = new CreatureProfile`,
    `        {`,
    `            Name = "${rc.name}", Scene = "res://assets/BadCreatures/${file}",`,
    `            Length = ${f(L)}, ModelLength = ${f(modelLength(c))}, Temperament = Temperament.${m.temperament},`,
    `            CruiseSpeed = ${f(cruise)}, PassSpeed = ${f(cruise * 1.8)}, TurnRate = ${f(Math.min(0.8, 1.4 / Math.sqrt(L)))}, CycleBase = ${f(m.cycle)}, CyclePerSpeed = ${f(m.cycle * 0.25)},`,
    `            EmissionEnergy = ${f(rc.mods.glow > 0 ? 2.6 : 3)}, WetSpec = 0.4f, Roughness = 0.6f,`,
  ];
  if (m.jaw) lines.push(`            Jaw = "${m.jaw.bone}", JawOpen = ${f(m.jaw.open - m.jaw.rest)}, JawClosed = ${f(m.jaw.closed - m.jaw.rest)},`);
  lines.push(`        };`);
  for (const ch of m.swim) {
    if (ch.axis === 'yaw') lines.push(`        p.Yaw.Add(("${ch.bone}", ${f(ch.amp)}, ${f(ch.phase)}, ${f(ch.curl ?? 0)}));`);
    else if (ch.axis === 'pitch') lines.push(`        p.Pitch.Add(("${ch.bone}", ${f(ch.amp)}, ${f(ch.phase)}));`);
    else lines.push(`        p.Roll.Add(("${ch.bone}", ${f(ch.amp)}, ${f(ch.phase)}));`);
  }
  if (m.bodySway) lines.push(`        p.BodySway = ${f(m.bodySway)};`);
  lines.push(`        return p;`, `    }`);
  return lines.join('\n') + '\n';
}
